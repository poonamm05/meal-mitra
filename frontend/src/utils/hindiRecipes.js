// Fallback helper to get Hindi recipe data
export const getHindiRecipe = (recipe) => {
  if (!recipe) return null;
  const directMatch = recipeHindiMap[recipe.name];
  if (directMatch) {
    return {
      name: directMatch.name,
      description: directMatch.description,
      cuisine: directMatch.cuisine || recipe.cuisine,
      difficulty: directMatch.difficulty || recipe.difficulty,
      ingredients: directMatch.ingredients,
      instructions: directMatch.instructions,
    };
  }

  // Fallback translation
  return {
    name: recipe.name,
    description: recipe.description,
    cuisine: recipe.cuisine,
    difficulty: recipe.difficulty,
    ingredients: (recipe.ingredients || []).map((ing) => ({
      ...ing,
      name: ing.name,
    })),
    instructions: recipe.instructions || [],
  };
};
